#!/usr/bin/env python3
"""Test-suite baseline guard for the src/fcp refactor.

WHY THIS EXISTS
---------------
The `src/fcp` rewrite keeps the protocol and wire format frozen, so the test
suite is the equivalence contract: every refactor step must leave ctest green
WITHOUT changing what the tests assert. A green run alone does not prove that --
a step that deletes an assertion, an entire test function, or a whole test
binary also turns ctest green. This script pins the shape of the suite so that
kind of silent erosion fails loudly.

WHAT IT CHECKS
--------------
  1. every test binary in tests/CMakeLists.txt still exists
  2. every binary still defines at least the baseline number of test functions
  3. every binary still carries at least the baseline number of CHECK/CHECK_EQ

The counts are a FLOOR, not an equality: adding a test for new behaviour is
always allowed (and is how a refactor proves a behaviour it had to make
explicit). Removing one is not.

USAGE
-----
    python3 scripts/test_baseline.py --write   # record / refresh the baseline
    python3 scripts/test_baseline.py           # verify against the baseline

The baseline lives in tests/test_baseline.json and is reviewed like code: a
commit that lowers a count has to say why.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TESTS = REPO / "tests"
BASELINE = TESTS / "test_baseline.json"
CMAKE = TESTS / "CMakeLists.txt"

# A test function is a free function with no arguments and a `void` return:
#   void TestSomething() {
# The suite deliberately has no test framework, so this is the whole contract.
TEST_FN = re.compile(r"^void\s+([A-Za-z_][A-Za-z_0-9]*)\s*\(\s*\)\s*\{", re.MULTILINE)
# CHECK(...) and CHECK_EQ(...); the optional `fcp_test::` / `::fcp_test::`
# qualification is how a couple of files spell it.
CHECK = re.compile(r"\bCHECK(_EQ)?\s*\(")


def listed_binaries():
    """Test names from tests/CMakeLists.txt (the FCP_TEST_NAMES list + extras).

    Parsed textually on purpose: this script must run on a machine with no
    CMake, and the file is small and stable.
    """
    text = CMAKE.read_text(encoding="utf-8")
    names = []

    match = re.search(r"set\(FCP_TEST_NAMES(.*?)\)", text, re.DOTALL)
    if match:
        for token in match.group(1).split():
            if not token.startswith("#"):
                names.append(token)

    # add_executable(fcp_<name> ...) targets outside the list (cli_test etc).
    for match in re.finditer(r"add_executable\(\s*(fcp_[A-Za-z_0-9]+)", text):
        target = match.group(1)[len("fcp_"):]
        if target not in names:
            names.append(target)

    return sorted(names)


def measure():
    """{test_name: {"functions": n, "checks": n}} for each expected binary."""
    expected = listed_binaries()
    seen = {path.stem: path for path in TESTS.glob("*_test.cc")}

    missing = [name for name in expected if name not in seen]
    if missing:
        for name in missing:
            print(f"ERROR: tests/{name}.cc is listed in CMakeLists.txt but missing")
        sys.exit(2)

    # A *_test.cc nobody builds is dead weight or a forgotten add_test; both
    # are worth knowing about, but only report it -- an experiment may sit
    # there half-wired without failing the gate.
    unlisted = sorted(set(seen) - set(expected))
    if unlisted:
        print(f"note: not built by ctest: {', '.join(unlisted)}")

    out = {}
    for name in expected:
        text = seen[name].read_text(encoding="utf-8", errors="replace")
        out[name] = {
            "functions": len(TEST_FN.findall(text)),
            "checks": len(CHECK.findall(text)),
        }
    return out


def write():
    current = measure()
    payload = {
        "_comment": (
            "Generated by scripts/test_baseline.py --write. Counts are FLOORS: "
            "the refactor may add tests, never remove them. Lower a number only "
            "in a commit that explains why."
        ),
        "binaries": current,
    }
    BASELINE.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    total_f = sum(v["functions"] for v in current.values())
    total_c = sum(v["checks"] for v in current.values())
    print(f"baseline written: {len(current)} binaries, {total_f} test functions, "
          f"{total_c} CHECKs -> {BASELINE.relative_to(REPO)}")


def verify():
    if not BASELINE.exists():
        print(f"ERROR: {BASELINE.relative_to(REPO)} missing; run --write once")
        return 2
    stored = json.loads(BASELINE.read_text(encoding="utf-8"))["binaries"]
    current = measure()

    problems = []
    for name, base in sorted(stored.items()):
        if name not in current:
            problems.append(f"{name}: test binary disappeared")
            continue
        got = current[name]
        for key, label in (("functions", "test functions"), ("checks", "CHECKs")):
            if got[key] < base[key]:
                problems.append(
                    f"{name}: {label} {base[key]} -> {got[key]} "
                    f"({base[key] - got[key]} removed)"
                )

    added = sorted(set(current) - set(stored))
    for name in problems:
        print(f"FAIL {name}")
    if added:
        print(f"note: new test binaries (refresh the baseline): {', '.join(added)}")

    if problems:
        print(f"\n{len(problems)} regression(s): the suite shrank. A refactor that "
              f"needs an assertion gone has to justify it explicitly.")
        return 1

    total_f = sum(v["functions"] for v in current.values())
    total_c = sum(v["checks"] for v in current.values())
    print(f"OK: {len(current)} binaries, {total_f} test functions, {total_c} CHECKs "
          f"(baseline met or exceeded)")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true",
                        help="record the current counts as the new baseline")
    args = parser.parse_args()
    return write() if args.write else verify()


if __name__ == "__main__":
    sys.exit(main() or 0)
